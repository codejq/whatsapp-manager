// Command gennotices writes THIRD_PARTY_NOTICES.md from the Go modules linked
// into the app, the npm packages bundled into the UI, and the bundled GoWA
// binary. Run from the repo root: go run ./tools/gennotices
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

type dep struct {
	Name, Version, License, Text, Source string
}

func main() {
	var deps []dep
	deps = append(deps, goDeps()...)
	deps = append(deps, npmDeps()...)
	sort.Slice(deps, func(i, j int) bool { return deps[i].Name < deps[j].Name })

	var b bytes.Buffer
	b.WriteString("# Third-party notices\n\n")
	b.WriteString("WhatsApp Manager is MIT licensed. It bundles or links the components below.\n")
	b.WriteString("This file is generated by `go run ./tools/gennotices`; do not edit by hand.\n\n")
	gowa, _ := os.ReadFile("LICENSES/GoWA-LICENSE.txt")
	b.WriteString("## GoWA (bundled binary)\n\n")
	b.WriteString("`whatsapp.exe` is the unmodified release binary of [go-whatsapp-web-multidevice](https://github.com/aldinokemal/go-whatsapp-web-multidevice) (version pinned in `build/gowa.version`). It includes its own dependencies, notably [whatsmeow](https://github.com/tulir/whatsmeow) (MPL-2.0).\n\n")
	b.WriteString("```\n" + strings.TrimSpace(string(gowa)) + "\n```\n\n")
	b.WriteString("## Fonts\n\nIBM Plex Sans Arabic and Inter are used under the SIL Open Font License 1.1 (via @fontsource packages).\n\n")
	b.WriteString("## Summary\n\n| Component | Version | License | Source |\n|---|---|---|---|\n")
	for _, d := range deps {
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", d.Name, d.Version, d.License, d.Source)
	}
	b.WriteString("\n## License texts\n\n")
	for _, d := range deps {
		if d.Text == "" {
			continue
		}
		fmt.Fprintf(&b, "### %s\n\n```\n%s\n```\n\n", d.Name, strings.TrimSpace(d.Text))
	}
	if err := os.WriteFile("THIRD_PARTY_NOTICES.md", b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote THIRD_PARTY_NOTICES.md (%d components)", len(deps))
}

func goDeps() []dep {
	cmd := exec.Command("go", "list", "-deps", "-f", "{{with .Module}}{{if not .Main}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}", "./cmd/whatsapp-manager")
	cmd.Env = append(os.Environ(), "GOOS=windows", "GOARCH=amd64", "CGO_ENABLED=0")
	out, err := cmd.Output()
	if err != nil {
		log.Fatal(err)
	}
	seen := map[string]bool{}
	var deps []dep
	for _, line := range strings.Split(string(out), "\n") {
		parts := strings.Split(strings.TrimSpace(line), "\t")
		if len(parts) != 3 || seen[parts[0]] {
			continue
		}
		seen[parts[0]] = true
		text := licenseText(parts[2])
		deps = append(deps, dep{Name: parts[0], Version: parts[1], License: detect(text), Text: text, Source: "https://" + parts[0]})
	}
	return deps
}

func npmDeps() []dep {
	cmd := exec.Command("npm", "ls", "--omit=dev", "--all", "--json", "--prefix", "web")
	if os.PathSeparator == '\\' {
		cmd = exec.Command("cmd", "/c", "npm", "ls", "--omit=dev", "--all", "--json", "--prefix", "web")
	}
	out, _ := cmd.Output()
	var tree struct {
		Dependencies map[string]json.RawMessage `json:"dependencies"`
	}
	if err := json.Unmarshal(out, &tree); err != nil {
		log.Printf("npm ls failed: %v", err)
		return nil
	}
	names := map[string]bool{}
	var walk func(map[string]json.RawMessage)
	walk = func(m map[string]json.RawMessage) {
		for name, raw := range m {
			names[name] = true
			var sub struct {
				Dependencies map[string]json.RawMessage `json:"dependencies"`
			}
			_ = json.Unmarshal(raw, &sub)
			walk(sub.Dependencies)
		}
	}
	walk(tree.Dependencies)
	var deps []dep
	for name := range names {
		dir := filepath.Join("web", "node_modules", filepath.FromSlash(name))
		var pkg struct {
			Version string `json:"version"`
			License any    `json:"license"`
		}
		b, err := os.ReadFile(filepath.Join(dir, "package.json"))
		if err != nil {
			continue
		}
		_ = json.Unmarshal(b, &pkg)
		lic := fmt.Sprint(pkg.License)
		if m, ok := pkg.License.(map[string]any); ok {
			lic = fmt.Sprint(m["type"])
		}
		deps = append(deps, dep{Name: "npm:" + name, Version: pkg.Version, License: lic, Text: licenseText(dir), Source: "https://www.npmjs.com/package/" + name})
	}
	return deps
}

func licenseText(dir string) string {
	entries, _ := os.ReadDir(dir)
	for _, e := range entries {
		n := strings.ToUpper(e.Name())
		if strings.HasPrefix(n, "LICENSE") || strings.HasPrefix(n, "LICENCE") || strings.HasPrefix(n, "COPYING") {
			b, err := os.ReadFile(filepath.Join(dir, e.Name()))
			if err == nil {
				return string(b)
			}
		}
	}
	return ""
}

func detect(text string) string {
	t := strings.ToLower(text)
	switch {
	case strings.Contains(t, "mozilla public license"):
		return "MPL-2.0"
	case strings.Contains(t, "apache license"):
		return "Apache-2.0"
	case strings.Contains(t, "permission is hereby granted, free of charge"):
		return "MIT"
	case strings.Contains(t, "redistribution and use in source and binary forms"):
		if strings.Contains(t, "neither the name") {
			return "BSD-3-Clause"
		}
		return "BSD-2-Clause"
	case strings.Contains(t, "permission to use, copy, modify, and/or distribute"):
		return "ISC"
	case strings.Contains(t, "unlicense"):
		return "Unlicense"
	case text == "":
		return "see source"
	}
	return "see text"
}
